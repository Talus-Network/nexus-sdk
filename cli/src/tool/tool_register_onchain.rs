/// Register a new onchain tool with automatic schema generation.
/// The input schema is automatically generated by introspecting the Move module's "execute" function.
/// todo: merge this function with the existing `tool_register.rs` function.
#[allow(clippy::too_many_arguments)]
pub(crate) async fn register_onchain_tool(
    package: sui::types::Address,
    module: sui::types::Identifier,
    fqn: ToolFqn,
    description: String,
    timeout: Duration,
    tool_witness_id: sui::types::Address,
    collateral_coin: Option<sui::types::Address>,
    invocation_cost_mist: u64,
    no_save: bool,
    sui_gas_coin: Option<sui::types::Address>,
    sui_gas_budget: u64,
) -> AnyResult<(), NexusCliError> {
    command_title!(
        "Registering Onchain Tool '{fqn}' from package '{package}::{module}'",
        fqn = fqn,
        package = package,
        module = module
    );

    if collateral_coin.is_some() && collateral_coin == sui_gas_coin {
        return Err(NexusCliError::Any(anyhow!(
            "The US collateral coin cannot be the same as the SUI gas coin."
        )));
    }

    let nexus_client = get_nexus_client(sui_gas_coin, sui_gas_budget).await?;
    if let Some(result) =
        super::tool_inspect::inspect_registration_result(&nexus_client, &fqn).await?
    {
        notify_success!(
            "Tool '{fqn}' is already registered.",
            fqn = fqn.to_string().truecolor(100, 100, 100)
        );
        json_output(&result)?;
        return Ok(());
    }

    let address = nexus_client.owner().map_err(NexusCliError::Nexus)?;
    let nexus_objects = nexus_client.get_nexus_objects();
    let context = nexus_client
        .context_for_root(&nexus_objects.tool_registry)
        .await
        .map_err(NexusCliError::Nexus)?;
    let collateral_coin = nexus_client
        .fetch_coin_by_type(collateral_coin, 0, nexus_objects.us_token.coin_type_tag())
        .await
        .map_err(NexusCliError::Nexus)?;

    // Generate and customize schemas.
    let (input_schema, output_schema, mode) =
        generate_and_customize_schemas(nexus_client.grpc_client(), package, &module).await?;

    let tx_handle = loading!("Crafting transaction...");

    let tx = match tool::register_on_chain_for_self_ptb(
        &context,
        package,
        module.as_str(),
        &fqn,
        &description,
        &input_schema,
        &output_schema,
        timeout,
        tool_witness_id,
        invocation_cost_mist,
        &collateral_coin,
        address,
        mode,
    ) {
        Ok(tx) => tx,
        Err(e) => {
            tx_handle.error();
            return Err(NexusCliError::Any(e));
        }
    };

    tx_handle.success();

    // Sign and submit the TX.
    let response = match nexus_client.submit_transaction(tx, address).await {
        Ok(response) => response,
        Err(e) => {
            if let Ok(Some(result)) =
                super::tool_inspect::inspect_registration_result(&nexus_client, &fqn).await
            {
                notify_success!(
                    "Tool '{fqn}' is already registered.",
                    fqn = fqn.to_string().truecolor(100, 100, 100)
                );
                json_output(&result)?;
                return Ok(());
            }

            notify_error!(
                "Failed to register tool '{fqn}': {error}",
                fqn = fqn.to_string().truecolor(100, 100, 100),
                error = e
            );

            return Err(NexusCliError::Nexus(e));
        }
    };

    // Extract the OwnerCap<OverTool> and OwnerCap<OverToolCashier> object IDs.
    let (over_tool_id, cashier_admin_id) = extract_owner_caps(&response.objects, &context)?;

    notify_success!(
        "Transaction digest: {digest}",
        digest = response.digest.to_string().truecolor(100, 100, 100)
    );

    // Save the owner caps to the CLI conf.
    if !no_save {
        save_tool_owner_caps(fqn.clone(), over_tool_id, cashier_admin_id).await?;
    }

    // Re-fetch the freshly-registered Tool object so the JSON output carries
    // the same shape `nexus tool inspect` emits. This costs one extra RPC
    // round-trip but means scripted consumers only need to learn one Tool
    // contract.
    let inspection = nexus_client
        .tool()
        .inspect_tool(&fqn)
        .await
        .map_err(NexusCliError::Nexus)?;
    let result = super::tool_inspect::registration_submission_result_json(
        &inspection,
        &response.digest,
        response.checkpoint,
        over_tool_id,
        cashier_admin_id,
    )?;
    json_output(&result)?;

    Ok(())
}

/// Generate input and output schemas and allow user customization.
async fn generate_and_customize_schemas(
    client: Arc<sui::grpc::Client>,
    package_address: sui::types::Address,
    module_name: &str,
) -> AnyResult<(String, String, OnchainToolMode), NexusCliError> {
    // Generate input schema by introspecting the Move module's "execute" function.
    let input_handle = loading!("Auto-generating input schema from Move module...");
    let (base_input_schema, mode) =
        match nexus_sdk::onchain_schema_gen::generate_input_schema_with_mode(
            client.clone(),
            package_address,
            module_name,
            "execute",
        )
        .await
        {
            Ok(generated) => {
                input_handle.success();
                generated
            }
            Err(e) => {
                input_handle.error();
                return Err(NexusCliError::Any(e));
            }
        };

    // Generate output schema by introspecting the Move module's "Output" enum.
    let output_handle = loading!("Auto-generating output schema from Move module...");
    let base_output_schema = match nexus_sdk::onchain_schema_gen::generate_output_schema(
        client,
        package_address,
        module_name,
        "Output",
    )
    .await
    {
        Ok(schema) => {
            output_handle.success();
            schema
        }
        Err(e) => {
            output_handle.error();
            return Err(NexusCliError::Any(e));
        }
    };

    // Allow user to customize parameter descriptions.
    let input_schema = customize_parameter_descriptions(base_input_schema)?;

    // Allow user to customize output variant and field descriptions.
    let output_schema = customize_output_variant_and_field_descriptions(base_output_schema)?;

    Ok((input_schema, output_schema, mode))
}

/// Extract the `OwnerCap<OverTool>` and `OwnerCap<OverToolCashier>` object IDs from the
/// transaction response.
fn extract_owner_caps(
    objects: &[sui::types::Object],
    context: &NexusContext,
) -> AnyResult<(sui::types::Address, Option<sui::types::Address>), NexusCliError> {
    let mut over_tool = None;
    let mut cashier_admin = None;

    for obj in objects {
        let sui::types::ObjectType::Struct(object_type) = obj.object_type() else {
            continue;
        };

        if !struct_tag_matches::<CloneableOwnerCap<OverTool>>(context, &object_type) {
            continue;
        }

        // Disambiguate by the generic type parameter. [`OverTool`] and
        // [`OverToolCashier`] are distinct authority markers in the Tool package.
        let Some(sui::types::TypeTag::Struct(inner)) = object_type.type_params().first() else {
            continue;
        };

        if struct_tag_matches::<OverTool>(context, inner) {
            over_tool = Some(obj.object_id());
        } else if struct_tag_matches::<OverToolCashier>(context, inner) {
            cashier_admin = Some(obj.object_id());
        }
    }

    let Some(over_tool_id) = over_tool else {
        return Err(NexusCliError::Any(anyhow!(
            "Could not find the OwnerCap<OverTool> object ID in the transaction response."
        )));
    };

    notify_success!(
        "OwnerCap<OverTool> object ID: {id}",
        id = over_tool_id.to_string().truecolor(100, 100, 100)
    );

    match cashier_admin {
        Some(cashier_admin_id) => notify_success!(
            "OwnerCap<OverToolCashier> object ID: {id}",
            id = cashier_admin_id.to_string().truecolor(100, 100, 100)
        ),
        None => {
            notify_success!(
                "No OwnerCap<OverToolCashier> was returned by the registration transaction."
            )
        }
    }

    Ok((over_tool_id, cashier_admin))
}

/// Save the tool owner caps to the CLI configuration.
async fn save_tool_owner_caps(
    fqn: ToolFqn,
    over_tool_id: sui::types::Address,
    cashier_admin_id: Option<sui::types::Address>,
) -> AnyResult<(), NexusCliError> {
    let save_handle = loading!("Saving the owner caps to the CLI configuration...");

    let mut conf = CliConf::load().await.unwrap_or_default();

    conf.tools.insert(
        fqn,
        ToolOwnerCaps {
            over_tool: over_tool_id,
            cashier_admin: cashier_admin_id,
        },
    );

    if let Err(e) = conf.save().await {
        save_handle.error();
        return Err(NexusCliError::Any(e));
    }

    save_handle.success();

    Ok(())
}

/// Represents a single parameter in the input schema.
#[derive(Debug, Clone, Serialize, Deserialize)]
struct ParameterSchema {
    #[serde(rename = "type")]
    param_type: String,
    description: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    mutable: Option<bool>,
}

/// Represents an output variant with optional fields.
#[derive(Debug, Clone, Serialize, Deserialize)]
struct OutputVariantSchema {
    #[serde(rename = "type", skip_serializing_if = "Option::is_none")]
    variant_type: Option<String>,
    description: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    fields: Option<Map<String, Value>>,
}

/// Allow the user to customize parameter descriptions interactively.
fn customize_parameter_descriptions_with_reader(
    schema_json: String,
    reader: &mut dyn std::io::BufRead,
) -> AnyResult<String, NexusCliError> {
    // Skip interactive prompts in JSON mode.
    if JSON_MODE.load(Ordering::Relaxed) {
        return Ok(schema_json);
    }

    // Deserialize into a typed map.
    let mut schema: HashMap<String, ParameterSchema> = serde_json::from_str(&schema_json)
        .map_err(|e| NexusCliError::Any(anyhow::anyhow!("Failed to parse schema JSON: {e}")))?;

    if schema.is_empty() {
        println!(
            "\n{info} No parameters to customize.",
            info = "▶".cyan().bold()
        );
        return Ok(schema_json);
    }

    println!(
        "\n{title}",
        title = "Input Schema Customization".bold().cyan()
    );
    println!("Customize descriptions for each input parameter (press Enter to keep current)");

    let mut param_keys = schema
        .keys()
        .map(|key| {
            key.parse::<usize>()
                .map(|index| (index, key.clone()))
                .map_err(|_| {
                    NexusCliError::Any(anyhow::anyhow!(
                        "On-chain input schema key '{key}' is not a positional index"
                    ))
                })
        })
        .collect::<AnyResult<Vec<_>, _>>()?;
    param_keys.sort_by_key(|(index, _)| *index);
    for (expected, (index, key)) in param_keys.iter().enumerate() {
        if *index != expected || key != &expected.to_string() {
            return Err(NexusCliError::Any(anyhow::anyhow!(
                "On-chain input schema keys must be contiguous positional indices starting at 0"
            )));
        }
    }

    // Customize each parameter.
    for (_, param_key) in &param_keys {
        if let Some(param) = schema.get_mut(param_key) {
            customize_parameter(param_key, param, reader)
                .map_err(|e| NexusCliError::Any(anyhow::anyhow!("I/O error: {e}")))?;
        }
    }

    println!();

    let mut final_schema = Map::new();
    for (_, param_key) in param_keys {
        let param = schema.remove(&param_key).ok_or_else(|| {
            NexusCliError::Any(anyhow::anyhow!(
                "On-chain input schema parameter '{param_key}' disappeared during customization"
            ))
        })?;
        let value = serde_json::to_value(param).map_err(|e| {
            NexusCliError::Any(anyhow::anyhow!("Failed to serialize parameter: {e}"))
        })?;
        final_schema.insert(param_key, value);
    }

    // Serialize back to JSON.
    serde_json::to_string(&final_schema)
        .map_err(|e| NexusCliError::Any(anyhow::anyhow!("Failed to serialize schema: {e}")))
}

/// Wrapper function that calls customize_parameter_descriptions_with_reader using stdin.
fn customize_parameter_descriptions(schema_json: String) -> AnyResult<String, NexusCliError> {
    let stdin = io::stdin();
    let mut reader = stdin.lock();
    customize_parameter_descriptions_with_reader(schema_json, &mut reader)
}

/// Allow the user to customize output variant and field descriptions through an interactive prompt.
fn customize_output_variant_and_field_descriptions_with_reader(
    base_schema: String,
    reader: &mut dyn std::io::BufRead,
) -> AnyResult<String, NexusCliError> {
    // Skip interactive prompts in JSON mode.
    if JSON_MODE.load(Ordering::Relaxed) {
        return Ok(base_schema);
    }

    // Deserialize into a typed map.
    let mut schema: HashMap<String, OutputVariantSchema> = serde_json::from_str(&base_schema)
        .map_err(|e| NexusCliError::Any(anyhow::anyhow!("Failed to parse output schema: {e}")))?;

    // Display header.
    println!(
        "\n{title}",
        title = "Output Schema Descriptions".bold().cyan()
    );
    println!(
        "Customize descriptions for output variants and their fields (press Enter to keep current)"
    );

    // Customize each variant.
    for (variant_name, variant) in schema.iter_mut() {
        customize_output_variant(variant_name, variant, reader)
            .map_err(|e| NexusCliError::Any(anyhow::anyhow!("I/O error: {e}")))?;
    }

    println!();

    // Serialize back to JSON.
    serde_json::to_string(&schema)
        .map_err(|e| NexusCliError::Any(anyhow::anyhow!("Failed to serialize output schema: {e}")))
}

/// Wrapper function that calls customize_output_variant_and_field_descriptions_with_reader using stdin.
fn customize_output_variant_and_field_descriptions(
    base_schema: String,
) -> AnyResult<String, NexusCliError> {
    let stdin = io::stdin();
    let mut reader = stdin.lock();
    customize_output_variant_and_field_descriptions_with_reader(base_schema, &mut reader)
}

/// Get a field's type and description from JSON value.
fn get_field_info(field_value: &Value) -> (String, String) {
    let field_type = field_value
        .get("type")
        .and_then(|v| v.as_str())
        .unwrap_or("unknown")
        .to_string();
    let description = field_value
        .get("description")
        .and_then(|v| v.as_str())
        .unwrap_or("No description")
        .to_string();
    (field_type, description)
}

/// Update a field's description in the JSON value.
fn update_field_description(field_value: &mut Value, new_description: String) {
    if let Some(obj) = field_value.as_object_mut() {
        obj.insert("description".to_string(), Value::String(new_description));
    }
}

/// Prompt the user for optional input with a default fallback.
fn prompt_optional_input(
    reader: &mut dyn std::io::BufRead,
    prompt: &str,
    current_value: &str,
) -> io::Result<Option<String>> {
    println!("Current: {}", current_value.truecolor(150, 150, 150));
    print!("{prompt}: ");
    io::stdout().flush()?;

    let mut input = String::new();
    reader.read_line(&mut input)?;
    let trimmed = input.trim();

    if trimmed.is_empty() {
        println!("{} Kept current value", "→".truecolor(150, 150, 150));
        Ok(None)
    } else {
        println!("{} Updated", "✓".green().bold());
        Ok(Some(trimmed.to_string()))
    }
}

/// Customize a single parameter interactively.
fn customize_parameter(
    param_key: &str,
    param: &mut ParameterSchema,
    reader: &mut dyn std::io::BufRead,
) -> io::Result<()> {
    let is_mutable = param.mutable.unwrap_or(false);
    let type_display = if is_mutable {
        format!("mut {}", param.param_type)
    } else {
        param.param_type.clone()
    };

    println!();
    println!(
        "{} Parameter {}: {} {}",
        "▶".purple().bold(),
        param_key.bold(),
        type_display.blue().bold(),
        if is_mutable {
            "(mutable)".yellow()
        } else {
            "".normal()
        }
    );

    // Customize parameter description.
    if let Some(new_desc) = prompt_optional_input(
        reader,
        "Custom description (Enter to keep)",
        &param.description,
    )? {
        param.description = new_desc;
    }

    Ok(())
}

/// Customize a single output field interactively.
fn customize_output_field(
    field_name: &str,
    field_value: &mut Value,
    reader: &mut dyn std::io::BufRead,
) -> io::Result<()> {
    let (field_type, description) = get_field_info(field_value);

    println!();
    println!(
        "{} Field {}: {}",
        "▶".purple().bold(),
        field_name.bold(),
        field_type.blue().bold()
    );

    if let Some(new_desc) =
        prompt_optional_input(reader, "Custom description (Enter to keep)", &description)?
    {
        update_field_description(field_value, new_desc);
    }

    Ok(())
}

/// Customize a single output variant interactively.
fn customize_output_variant(
    variant_name: &str,
    variant: &mut OutputVariantSchema,
    reader: &mut dyn std::io::BufRead,
) -> io::Result<()> {
    println!();
    println!(
        "{} Variant {}: {}",
        "▶".purple().bold(),
        variant_name.bold(),
        "variant".blue().bold()
    );

    // Customize variant description.
    if let Some(new_desc) = prompt_optional_input(
        reader,
        "Custom description (Enter to keep)",
        &variant.description,
    )? {
        variant.description = new_desc;
    }

    // Customize field descriptions if present.
    if let Some(fields) = &mut variant.fields {
        for (field_name, field_value) in fields.iter_mut() {
            customize_output_field(field_name, field_value, reader)?;
        }
    }

    Ok(())
}

